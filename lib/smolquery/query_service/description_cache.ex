defmodule Smolquery.QueryService.DescriptionCache do
  @moduledoc """
  What each sealed file says about its columns, kept on the node once a
  shard has read it (T-723).

  A shard reads the field ids of every sealed file whose catalog entry
  carries none before it scans (`Smolquery.QueryService.ShardDescribe`), one
  S3 footer read a file, and it read them again on every query: a table
  registered by hand (`bench.hits_x10`, 1,730 files) paid them on every
  shard of every query. A file is keyed by its URL, the snapshot that
  registered it, and its size: a file registered again at the same URL, as
  a table regenerated by hand would be, is a new key and is read again. So
  the second query on the node reads none of the footers the first read.

  ## Reads and their bounds

  - `fetch/2` is one `:ets.lookup/2` a file on a `:set`: constant a file,
    proportional to what it returns.
  - `put/4` is one `:ets.insert/2` of what a shard just read.

  ## The ceiling and how it shrinks

  At most `max_entries/0` files are kept, 10,000 unless
  `config :smolquery, Smolquery.QueryService.DescriptionCache, max_entries:`
  says otherwise. An entry holds a file's top-level column names and their
  ids, about 100 bytes a column, so 10,000 entries of 100 columns is about
  100 MB. The names are copied out of the Arrow buffers they were read from,
  so an entry holds only itself. A `put/4` that would pass the ceiling
  empties the table first, and keeps at most the ceiling of what it was
  given. A reset costs the next queries their footer reads again, which is
  what every query paid before this cache, and needs no eviction order to be
  kept right. A working set larger than the ceiling resets on most queries
  and gains nothing; the ceiling is sized well above one hand-registered
  table's file count.

  A table that is not there, a burst runner's standalone shard or one
  restarting under its supervisor, holds nothing and keeps nothing: the
  shard reads every file, as before.
  """

  use GenServer

  alias Smolquery.QueryService.Runtime
  alias Smolquery.Segments.FieldIds

  @type file :: %{required(String.t()) => term()}

  @default_max_entries 10_000

  @doc """
  The most files the cache keeps (application config `:max_entries`, 10,000).
  """
  @spec max_entries() :: pos_integer()
  def max_entries do
    :smolquery
    |> Application.get_env(__MODULE__, [])
    |> Keyword.get(:max_entries, @default_max_entries)
  end

  @doc false
  @spec start_link(Runtime.t()) :: GenServer.on_start()
  def start_link(%Runtime{} = runtime) do
    table = Runtime.description_cache(runtime.name)
    GenServer.start_link(__MODULE__, table, name: Module.concat(table, "Owner"))
  end

  @doc """
  The descriptions `table` holds for `files` (the request's file maps, with
  `"url"`, `"snapshot"` and `"bytes"`), by URL, and the URLs of the files it
  holds none for.
  """
  @spec fetch(atom() | nil, [file()]) ::
          {%{String.t() => FieldIds.description()}, [String.t()]}
  def fetch(nil, files), do: {%{}, Enum.map(files, & &1["url"])}

  def fetch(table, files) do
    looked_up = Enum.map(files, &{&1["url"], lookup(table, key(&1))})

    {for({url, [{_key, description}]} <- looked_up, into: %{}, do: {url, description}),
     for({url, []} <- looked_up, do: url)}
  end

  @doc """
  Keeps `described`, a map of URL to description read for `files`, in
  `table`, emptying it first when it would pass `max_entries`.
  """
  @spec put(atom() | nil, [file()], %{String.t() => FieldIds.description()}, pos_integer()) ::
          :ok
  def put(nil, _files, _described, _max_entries), do: :ok
  def put(_table, _files, described, _max_entries) when map_size(described) == 0, do: :ok

  def put(table, files, described, max_entries) do
    entries =
      for %{"url" => url} = file <- files,
          description = Map.get(described, url),
          description != nil,
          do: {{:binary.copy(url), file["snapshot"], file["bytes"]}, copied(description)}

    with size when is_integer(size) <- :ets.info(table, :size) do
      if size + length(entries) > max_entries, do: :ets.delete_all_objects(table)
      :ets.insert(table, Enum.take(entries, max_entries))
    end

    :ok
  rescue
    ArgumentError -> :ok
  end

  @impl GenServer
  def init(table) do
    :ets.new(table, [
      :named_table,
      :public,
      :set,
      read_concurrency: true,
      write_concurrency: true
    ])

    {:ok, table}
  end

  defp lookup(table, key) do
    :ets.lookup(table, key)
  rescue
    ArgumentError -> []
  end

  defp key(file), do: {file["url"], file["snapshot"], file["bytes"]}

  defp copied(%{ids: ids, columns: columns}) do
    %{
      ids: ids && Map.new(ids, fn {name, id} -> {:binary.copy(name), id} end),
      columns: Enum.map(columns, &:binary.copy/1)
    }
  end
end
